export function getSkillsForService(serviceName) {
  if (!serviceName) return [];
  const cat = WORKER_SERVICES_CATALOG.find(
    (c) => c.name.toLowerCase() === serviceName.toLowerCase() || c.id.toLowerCase() === serviceName.toLowerCase()
  );
  return cat ? cat.defaultSkills : [];
}

export function getCategoryByName(serviceName) {
  if (!serviceName) return null;
  return WORKER_SERVICES_CATALOG.find(
    (c) => c.name.toLowerCase() === serviceName.toLowerCase() || c.id.toLowerCase() === serviceName.toLowerCase()
  ) || null;
}
